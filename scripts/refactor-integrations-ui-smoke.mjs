import { chromium } from "playwright-core";
import assert from "node:assert/strict";
import fs from "node:fs";
import { installMockBridge } from "./qa-bridge.mjs";

const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage();
const errors = [], checks = {};
page.on("pageerror", error => errors.push(error.message));
await page.addInitScript(installMockBridge);
try {
  await page.goto(process.env.GROK_DESKTOP_DEV_URL || "http://127.0.0.1:5180");
  await page.locator(".topbar-connection .online").waitFor();
  await page.evaluate(async () => {
    const React = (await import("/node_modules/.vite/deps/react.js")).default;
    const { createRoot } = (await import("/node_modules/.vite/deps/react-dom_client.js")).default;
    const { McpPage } = await import("/src/components/settings/McpPage.tsx");
    const node = document.createElement("div"); node.id = "mcp-fixture";
    node.style.cssText = "position:fixed;inset:0;z-index:9999;background:var(--bg);overflow:auto;padding:24px";
    document.body.append(node);
    const servers = [{ name: "local-tools", transport: "stdio", command: "node", args: ["server.mjs"], envKeys: ["TOKEN"], scope: "user", enabled: true }];
    window.__mcpSpecs = []; window.__mcpRestarts = 0;
    window.grokDesktop.listMcpServers = async () => ({ ok: true, servers });
    window.grokDesktop.addMcpServer = async spec => { window.__mcpSpecs.push(spec); return { ok: true }; };
    window.grokDesktop.doctorMcp = async () => ({ ok: true, servers: [{ name: "local-tools", healthy: true, checks: [], tools: ["read"], toolCount: 1 }] });
    window.__mcpRoot = createRoot(node);
    window.__mcpRoot.render(React.createElement(McpPage, { open: true, focus: false, hasProject: true, restarting: false, onRestartAfterWrite: async () => { window.__mcpRestarts++; } }));
  });
  const fixture = page.locator("#mcp-fixture");
  await fixture.getByRole("button", { name: "Edit", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Edit local-tools" });
  assert.equal(await dialog.locator('input[type=password]').inputValue(), "", "stored secret values are never hydrated");
  await dialog.getByLabel("Args", { exact: true }).fill("server.mjs --port 3000");
  await dialog.locator('input[type=password]').fill("qa-replacement");
  await dialog.getByRole("button", { name: "Save", exact: true }).click();
  await dialog.waitFor({ state: "hidden" });
  const edited = await page.evaluate(() => window.__mcpSpecs[0]);
  assert.equal(edited.name, "local-tools"); assert.equal(edited.command, "node");
  assert.deepEqual(edited.args, ["server.mjs", "--port", "3000"]);
  assert.deepEqual(edited.env, [{ key: "TOKEN", value: "qa-replacement" }]);
  checks.editKeepsCliContractAndSecretBoundary = true;
  await fixture.getByRole("button", { name: "Test", exact: true }).click();
  await fixture.getByText("Healthy · 1 tool", { exact: true }).waitFor();
  checks.doctorPresentation = true;
  await fixture.getByRole("button", { name: "Add server", exact: true }).click();
  const add = page.getByRole("dialog", { name: "Add server", exact: true });
  await add.getByLabel("Name", { exact: true }).fill("remote-tools");
  await add.getByRole("combobox", { name: "MCP transport" }).selectOption("http");
  await add.getByLabel("URL", { exact: true }).fill("https://example.com/mcp");
  await add.getByRole("checkbox", { name: /Project scope/ }).check();
  await add.getByRole("button", { name: "Add", exact: true }).click();
  await add.waitFor({ state: "hidden" });
  const created = await page.evaluate(() => window.__mcpSpecs[1]);
  assert.equal(created.transport, "http"); assert.equal(created.url, "https://example.com/mcp"); assert.equal(created.scope, "project");
  assert.equal(await page.evaluate(() => window.__mcpRestarts), 2);
  checks.transportAndProjectScope = true;
  assert.deepEqual(errors, []);
  await page.evaluate(() => window.__mcpRoot.unmount());
  fs.writeFileSync("qa/refactor-integrations.json", JSON.stringify(checks, null, 2));
  console.log("REFACTOR_INTEGRATIONS_OK", checks);
} finally { await browser.close(); }
